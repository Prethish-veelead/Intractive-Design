await m.goto(base + "/th"); await m.waitForTimeout(1200);
await m.evaluate(() => window.scrollTo(0, 1200)); await m.waitForTimeout(700);
r.headerBlur = await m.locator("header nav").evaluate((e) => getComputedStyle(e).backdropFilter);
await m.screenshot({ path: out + "/8-mobile-header-blur.png" });
await m.evaluate(() => window.scrollTo(0, 0));
await m.getByRole("button", { name: "เมนู" }).click(); await m.waitForTimeout(900);
await m.screenshot({ path: out + "/9-mobile-menu.png" });
r.errors = errors;
console.log(JSON.stringify(r, null, 1));
await b.close();
