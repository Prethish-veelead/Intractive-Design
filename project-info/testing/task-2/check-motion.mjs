// Task 2 motion checks. Run from the project root against a running server:
//   npx next start -p 3123  then  node project-info/testing/task-2/check-motion.mjs
import { chromium } from "@playwright/test";
const out = "project-info/testing/task-2", base = "http://localhost:3123";
const r = {}; const errors = [];
const b = await chromium.launch();
const watch = (p) => {
  p.on("pageerror", (e) => errors.push("pageerror " + e.message));
  p.on("console", (m) => m.type() === "error" && !m.text().includes("404") && errors.push("console " + m.text()));
};
const d = await b.newPage({ viewport: { width: 1440, height: 900 } }); watch(d);
await d.goto(base + "/th"); await d.waitForTimeout(250);
r.heroMidIntro = await d.locator(".hero-line > span").first().evaluate((e) => getComputedStyle(e).transform);
await d.screenshot({ path: out + "/1-hero-intro-midway.png" });
await d.waitForTimeout(1500);
r.heroAfterIntro = await d.locator(".hero-line > span").first().evaluate((e) => getComputedStyle(e).transform);
await d.screenshot({ path: out + "/2-hero-settled.png" });
const track = d.locator("ul.touch-pan-y");
await track.scrollIntoViewIfNeeded(); await d.waitForTimeout(900);
const box = await track.boundingBox(); const startUrl = d.url();
await d.mouse.move(box.x + 600, box.y + 150); await d.mouse.down();
await d.mouse.move(box.x + 300, box.y + 150, { steps: 30 });
await d.waitForTimeout(200); await d.mouse.up(); await d.waitForTimeout(1500);
r.carouselAfterDrag = await track.evaluate((e) => e.style.transform);
r.urlUnchangedAfterDrag = d.url() === startUrl;
const next = d.getByRole("button", { name: "ถัดไป" }), prev = d.getByRole("button", { name: "ก่อนหน้า" });
await ((await next.isDisabled()) ? prev : next).click(); await d.waitForTimeout(900);
r.carouselAfterButton = await track.evaluate((e) => e.style.transform);
await d.screenshot({ path: out + "/3-carousel-dragged.png" });
for (let y = 0; y < 9000; y += 500) { await d.mouse.wheel(0, 500); await d.waitForTimeout(120); }
await d.waitForTimeout(1200);
r.revealStillHidden = await d.locator("main [data-reveal]:visible").evaluateAll((els) => els.filter((e) => getComputedStyle(e).opacity !== "1").length);
r.pinSpacer = await d.locator(".pin-spacer").count();
r.shimmerRevealed = await d.locator(".is-revealed .shimmer, .shimmer.is-revealed").count();
await d.locator("blockquote").first().scrollIntoViewIfNeeded(); await d.waitForTimeout(600);
await d.screenshot({ path: out + "/4-brand-story-pinned.png" });
await d.goto(base + "/en/shop/lips"); await d.waitForTimeout(800);
await d.locator("main a[href='/en/product/velvet-kiss-matte-lipstick']").hover(); await d.waitForTimeout(600);
await d.screenshot({ path: out + "/5-card-hover-second-shade.png" });
await d.locator("main a[href='/en/product/velvet-kiss-matte-lipstick']").click();
await d.waitForURL("**/product/velvet-kiss-matte-lipstick"); await d.waitForTimeout(800);
await d.getByRole("button", { name: "Mulberry" }).click(); await d.waitForTimeout(700);
await d.getByRole("button", { name: "Add to bag" }).click(); await d.waitForTimeout(450);
r.addedVisible = await d.getByText("Added", { exact: true }).first().isVisible();
r.bagLabel = await d.locator("header a[href='/en/bag']").getAttribute("aria-label");
await d.screenshot({ path: out + "/6-added-to-bag.png" });
const knob = d.getByRole("slider");
await knob.focus(); await d.keyboard.press("ArrowRight"); await d.keyboard.press("ArrowRight");
r.sliderAfterKeys = await knob.getAttribute("aria-valuenow");
const kb = await knob.boundingBox();
await d.mouse.move(kb.x + kb.width / 2, kb.y + kb.height / 2); await d.mouse.down();
await d.mouse.move(kb.x + kb.width / 2 - 150, kb.y + kb.height / 2, { steps: 8 }); await d.mouse.up();
r.sliderAfterDrag = await knob.getAttribute("aria-valuenow");
await knob.scrollIntoViewIfNeeded(); await d.screenshot({ path: out + "/7-compare-slider.png" });
await d.waitForTimeout(1500);
r.addedResets = await d.getByRole("button", { name: "Add to bag" }).isVisible();
const rm = await (await b.newContext({ viewport: { width: 375, height: 812 }, reducedMotion: "reduce" })).newPage(); watch(rm);
await rm.goto(base + "/th"); await rm.waitForTimeout(400);
r.rmHeroTransform = await rm.locator(".hero-line > span").first().evaluate((e) => getComputedStyle(e).transform);
r.rmHiddenReveals = await rm.locator("main [data-reveal]").evaluateAll((els) => els.filter((e) => getComputedStyle(e).opacity !== "1").length);
